"""
Core Data Types & Pydantic Models for StudyMate.

This module defines the foundational message, tool call, and response data
structures used across the entire agent harness—including the ReAct engine,
ContextManager, LLM clients, tool registry, and observability layers.
"""

from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class Role(str, Enum):
    """
    Standard chat conversation roles in an agent conversation turn.
    
    Attributes:
        SYSTEM: System instructions, persona prompt, or injected context.
        USER: Student input messages or continuation prompts.
        ASSISTANT: Agent reasoning, textual answers, or tool call requests.
        TOOL: Observation output returned after executing a tool.
    """
    SYSTEM = "system"
    USER = "user"
    ASSISTANT = "assistant"
    TOOL = "tool"


class ToolCall(BaseModel):
    """
    Represents a function call decision requested by the LLM during reasoning.
    
    Attributes:
        id: Unique identifier generated by the LLM endpoint for tracking.
        name: Function/tool name to invoke (e.g., 'read_file', 'delegate_task').
        arguments: Key-value dictionary of arguments passed to the tool.
    """
    id: str = Field(description="Unique tool call identifier")
    name: str = Field(description="Name of the function to invoke")
    arguments: Dict[str, Any] = Field(default_factory=dict, description="Parsed arguments for the function")


class ToolResult(BaseModel):
    """
    Represents the execution observation returned by a tool to the agent.
    
    Attributes:
        tool_call_id: The ID of the ToolCall this result satisfies.
        name: The name of the tool executed.
        content: The text output or observation returned by the tool.
        is_error: True if the tool execution encountered an error.
    """
    tool_call_id: str
    name: str
    content: str
    is_error: bool = False


class ChatMessage(BaseModel):
    """
    Standard unified message format across all StudyMate harness components.
    
    Encapsulates all possible message types (user prompts, system directives,
    assistant thoughts/tool calls, and tool execution results) and provides
    serialization compatible with the OpenAI Chat Completion API.
    """
    role: Role
    content: Optional[str] = None
    tool_calls: Optional[List[ToolCall]] = None
    tool_call_id: Optional[str] = None
    name: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        """
        Serializes the ChatMessage into an OpenAI-compatible JSON dictionary.
        
        Handles JSON stringification of tool call arguments to guarantee
        seamless communication with LLM inference endpoints.
        """
        import json as _json
        data: Dict[str, Any] = {"role": self.role.value}
        if self.content is not None:
            data["content"] = self.content
        if self.tool_calls:
            data["tool_calls"] = [
                {
                    "id": tc.id,
                    "type": "function",
                    "function": {
                        "name": tc.name,
                        "arguments": tc.arguments if isinstance(tc.arguments, str) else _json.dumps(tc.arguments)
                    }
                }
                for tc in self.tool_calls
            ]
        if self.tool_call_id:
            data["tool_call_id"] = self.tool_call_id
        if self.name:
            data["name"] = self.name
        return data



class LLMResponse(BaseModel):
    """
    Structured container for raw output returned by an LLM inference call.
    
    Captures assistant content, optional reasoning/thinking chains, parsed
    tool calls, stop reasons, and token usage breakdown.
    """
    content: Optional[str] = None
    reasoning_content: Optional[str] = Field(
        default=None,
        description="Chain-of-thought text when the provider exposes it "
        "(e.g. reasoning_content); None when the endpoint omits it.",
    )
    tool_calls: List[ToolCall] = Field(default_factory=list)
    finish_reason: Optional[str] = None
    prompt_tokens: int = 0
    completion_tokens: int = 0
    total_tokens: int = 0
    reasoning_tokens: int = 0
    raw_response: Optional[Dict[str, Any]] = None


class AgentRunResult(BaseModel):
    """
    Result of a complete end-to-end agent execution turn (ReAct loop).
    
    Contains the final synthesized response, iteration count, token consumption,
    observability run IDs, and success status for the REPL and telemetry systems.
    """
    final_response: str = ""
    iterations: int = 0
    tool_calls_count: int = 0
    prompt_tokens: int = 0
    completion_tokens: int = 0
    total_tokens: int = 0
    reasoning_tokens: int = 0
    is_success: bool = True
    error_message: Optional[str] = None
    run_id: Optional[str] = None
    parent_run_id: Optional[str] = None
    metadata: Dict[str, Any] = Field(default_factory=dict)

